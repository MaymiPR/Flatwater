"""Writes plugins/FwDelay/Source/dsp/AnalogTables.h: the reference's Analog modes (measurements/FwDelay/analog_model.json from
plugins/FwComp/nulltest/fit_analog.py with ANALOG_PREFIX=hd, the noise from analog_noise.csv), in Flatwater Comp's Analog format (mode 4
is the reference's: they null at -100 dB).

    python plugins/FwDelay/scripts/export_analog_tables.py
"""
import os, sys
sys.path.append(os.path.dirname(os.path.abspath(__file__)))
sys.path.append(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..', 'FwComp', 'scripts'))   # plugins/FwComp/scripts/
import export_tables as W

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..', '..')


def main():
    W.M = os.path.join(ROOT, 'measurements', 'FwDelay')
    def lit(t):
        s = '%.9g' % float(t)
        return (s if ('.' in s or 'e' in s) else s + '.0') + 'f'
    f = lambda v: ', '.join(lit(t) for t in v)
    body = W.analog(lit, f)
    # the format (counts, knots, the struct) is Flatwater Comp's: keep only the table itself, in Flatwater Delay's namespace
    start = next(i for i, l in enumerate(body) if l.startswith('constexpr AnalogMode analog['))
    L = ['#pragma once', '// Generated by plugins/FwDelay/scripts/export_analog_tables.py from measurements/FwDelay (the reference H-Delay). Do not edit.',
         '#include "plugins/FwComp/Source/dsp/Tables.h"', 'namespace de::tables', '{',
         '// H-Delay\'s Analog modes in Flatwater Comp\'s format (co::tables::AnalogMode); mode 4 is H-Comp\'s',
         'using co::tables::AnalogMode;',
         body[start].replace('analogModes', 'co::tables::analogModes')] + body[start + 1:] + ['}', '']
    out = os.path.join(ROOT, 'plugins', 'FwDelay', 'Source', 'dsp', 'AnalogTables.h')
    open(out, 'w', encoding='utf-8').write('\n'.join(L))
    print('wrote', out)


if __name__ == '__main__':
    main()
