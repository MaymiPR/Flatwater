"""Writes plugins/FwVocalChain/Source/dsp/DeEss.h from the main de-esser's fit (nulltest/fit_deess.py fit): the parameters,
the look-ahead (samples at 48 kHz) and the zero-phase high band's taps per rate.

    python -I export_deess.py
"""
import json
import os
import sys
import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.append(os.path.join(HERE, '..', 'nulltest'))   # plugins/FwVocalChain/nulltest/
import fit_deess as F


def header():
    """writes plugins/FwVocalChain/Source/dsp/DeEss.h: the parameters, the look-ahead (samples at 48 kHz) and the high band's
    taps per rate (designed at 44.1 / 88.2 / 96 kHz from the 48 kHz band's response, whole above 20 kHz)"""
    js = json.load(open(F.PARAMS))
    h = np.array(js['h'])
    fgrid = np.linspace(0, 24000, 4801)
    H48 = h[0] + 2 * sum(h[k] * np.cos(2 * np.pi * fgrid * k / F.FS) for k in range(1, F.NT + 1))
    rows = []
    for fs in (44100, 48000, 88200, 96000):
        if fs == 48000: c = h
        else:
            nt = int(round(F.NT * fs / F.FS))
            f = np.linspace(0, fs / 2, 4001)
            target = np.where(f <= 20000, np.interp(f, fgrid, H48), 1.0)
            A = np.stack([np.ones(len(f))] + [2 * np.cos(2 * np.pi * f * k / fs) for k in range(1, nt + 1)], 1)
            c, *_ = np.linalg.lstsq(A, target, rcond=None)
            e = A @ c - target
            print('%d: %d taps, residual %.1f dB' % (fs, 2 * nt + 1, 10 * np.log10(np.sum(e ** 2) / np.sum(target ** 2))))
        rows.append('{ %d.0, %d, { %s } }' % (fs, len(c) - 1, ', '.join('%.17g' % v for v in c)))
    out = os.path.join(HERE, '..', 'Source', 'dsp', 'DeEss.h')
    lines = ['#pragma once', "// Generated by plugins/FwVocalChain/scripts/export_deess.py from Phase 4's fit of the main de-esser: its parameters (plugins/FwVocalChain/nulltest/native/DeEss.c's",
             '// order: ' + ' '.join(F.NAMES) + '),', "// the look-ahead in samples at 48 kHz, and the zero-phase high band's taps per rate (h[0] the",
             '// centre, h[k] = h[-k]). Do not edit.', 'namespace ch::deesstables', '{',
             'inline constexpr int nParams = %d;' % len(F.NAMES),
             'inline constexpr double p[nParams] = { %s };' % ', '.join('%.9g' % v for v in js['p']),
             'inline constexpr int lookAhead48 = %d;' % js['la'],
             'struct Taps { double fs; int nt; double h[49]; };',
             'inline constexpr Taps taps[4] = { %s };' % ', '.join(rows), '}', '']
    open(out, 'w', newline='\n').write('\n'.join(lines))
    print('wrote', out)


if __name__ == '__main__':
    header()
